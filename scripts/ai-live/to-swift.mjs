// Turns a harness recording into a Swift test fixture (real OpenAI replies, synthetic data only).
//   node to-swift.mjs <recordings.json> <LiveRecordings.swift>
import { readFileSync, writeFileSync } from "node:fs";
const [inp, out] = process.argv.slice(2);
const rec = JSON.parse(readFileSync(inp, "utf8"));
const json = JSON.stringify(rec);
if (json.includes('"""##')) throw new Error("delimiter clash");
writeFileSync(out, `// Generated by scripts/ai-live/to-swift.mjs from a live run of ${rec.model} — do not edit.
// Every assistant message below is a real OpenAI reply to the app's exact tools and prompt (synthetic data).
enum LiveRecordings {
    static let json = ##"""
${json}
"""##
}
`);
console.log("scenarios", rec.recordings.length, "bytes", json.length);
